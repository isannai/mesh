// parseBatch turns a generation response into questions.
//
// The first two usable lines become the few-shot pair and are NOT returned as
// questions — their answers are already in the prompt, so asking them would
// measure copying rather than knowledge.
//
// Lines that do not parse are skipped rather than failing the batch: models
// intersperse numbering and stray prose no matter how the prompt is worded, and
// one bad line should not cost the other nineteen.
func parseBatch(cat Category, raw string) []Question {
	var pairs []QA
	for _, line := range strings.Split(raw, "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		parts := strings.SplitN(line, "|", 2)
		if len(parts) != 2 {
			continue
		}
		q := strings.TrimSpace(parts[0])
		a := strings.TrimSpace(parts[1])
		// Strip a leading "1." / "1)" the model added despite being told not to.
		q = strings.TrimSpace(strings.TrimLeft(q, "0123456789.)- "))
		if q == "" || a == "" {
			continue
		}
		// A multi-sentence answer means the model ignored the format; scoring
		// only looks at the first few tokens so it would fail anyway.
		if len(a) > 40 || strings.Contains(a, "|") {
			continue
		}
		pairs = append(pairs, QA{Q: q, A: a})
	}
	if len(pairs) < 3 {
		return nil // not enough to spare two for examples
	}

	fewshot := []QA{pairs[0], pairs[1]}
	out := make([]Question, 0, len(pairs)-2)
	for _, p := range pairs[2:] {
		out = append(out, Question{Category: cat, Q: p.Q, Draft: p.A, Fewshot: fewshot})
	}
	return out
}
